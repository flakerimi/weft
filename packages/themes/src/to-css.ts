import { colorKeys, type ColorSet, type Curve, type Theme } from './tokens.ts'

const curve = (c: Curve) => `cubic-bezier(${c.join(', ')})`

function colors(theme: Theme, scheme: 'light' | 'dark'): string[] {
  const set: Partial<ColorSet> = theme[scheme] ?? {}
  return colorKeys.map((key) => {
    const value = set[key]
    if (!value) throw new Error(`theme "${theme.name}" is missing ${scheme}.${key}`)
    return `  --weft-color-${key}: ${value};`
  })
}

const block = (selector: string, lines: string[]) => `${selector} {\n${lines.join('\n')}\n}`

/** Render a theme as CSS custom properties, including scheme and density blocks. */
export function themeToCss(theme: Theme): string {
  const light = colors(theme, 'light')
  const dark = colors(theme, 'dark')
  const shared = [
    `  color-scheme: light;`,
    ...light,
    ...Object.entries(theme.space).map(([k, v]) => `  --weft-space-${k}: ${v}px;`),
    ...Object.entries(theme.radius).map(([k, v]) => `  --weft-radius-${k}: ${v}px;`),
    ...Object.entries(theme.motion).map(([k, v]) => `  --weft-duration-${k}: ${v}ms;`),
    `  --weft-ease-standard: ${curve(theme.ease.standard)};`,
    `  --weft-ease-emphasized: ${curve(theme.ease.emphasized)};`,
    `  --weft-font-sans: ${theme.font.sans};`,
    `  --weft-font-mono: ${theme.font.mono};`,
    `  --weft-weight-body: ${theme.font.weightBody};`,
    `  --weft-weight-heading: ${theme.font.weightHeading};`,
    `  --weft-weight-title: ${theme.font.weightTitle};`,
    `  --weft-control-height: 36px;`,
    `  --weft-hit-min: 24px;`,
    `  --weft-text-base: 14px;`,
    `  --weft-page-max: none;`,
    `  --weft-section-gap: var(--weft-space-6);`,
  ]
  const darkLines = ['  color-scheme: dark;', ...dark]
  return [
    `/* Weft theme: ${theme.name}. Generated by @weft/themes; do not edit. */`,
    block(':root, [data-weft-scheme="light"]', shared),
    block('[data-weft-scheme="dark"]', darkLines),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-weft-scheme="light"])', darkLines)}\n}`,
    block('[data-weft-input="pointer"]', ['  --weft-control-height: 36px;', '  --weft-hit-min: 24px;']),
    block('[data-weft-input="touch"]', ['  --weft-control-height: 44px;', '  --weft-hit-min: 44px;']),
    block('[data-weft-surface="landing"]', [
      '  --weft-text-base: 18px;', '  --weft-page-max: 1200px;', '  --weft-section-gap: var(--weft-space-8);',
    ]),
    block('[data-weft-surface="app"]', [
      '  --weft-text-base: 14px;', '  --weft-page-max: none;', '  --weft-section-gap: var(--weft-space-6);',
    ]),
    '',
  ].join('\n\n')
}
